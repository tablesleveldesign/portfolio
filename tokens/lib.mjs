// Token helpers shared by the build script, the tests, and the TokenExplorer island.
// Plain JS so Node can run it without a compile step; types live in lib.d.mts.

export const THEMES = /** @type {const} */ (['light', 'dark']);

/** Look up a dotted path like "color.neutral.50" inside the primitives. */
export function getPrimitive(tokens, path) {
  const value = path.split('.').reduce((node, key) => node?.[key], tokens.primitive);
  if (typeof value !== 'string') throw new Error(`Unknown primitive: ${path}`);
  return value;
}

/** Resolve "{color.neutral.50}" references; literal values pass through. */
export function resolveValue(tokens, value) {
  const match = /^\{(.+)\}$/.exec(value);
  return match ? getPrimitive(tokens, match[1]) : value;
}

/** Every semantic token for one theme, resolved to a raw value. */
export function resolveTheme(tokens, theme) {
  const semantic = tokens.semantic[theme];
  if (!semantic) throw new Error(`Unknown theme: ${theme}`);
  return Object.fromEntries(Object.entries(semantic).map(([name, ref]) => [name, resolveValue(tokens, ref)]));
}

/** Flatten a nested primitive group into [name, value] pairs: {size: {0: x}} -> ["size-0", x]. */
function flatten(node, prefix) {
  return Object.entries(node).flatMap(([key, value]) =>
    typeof value === 'string' ? [[`${prefix}-${key}`, value]] : flatten(value, `${prefix}-${key}`),
  );
}

const cssVars = (pairs, indent = '  ') => pairs.map(([name, value]) => `${indent}--${name}: ${value};`).join('\n');

/**
 * Generate the CSS custom properties.
 * Light is the default. Dark applies from the OS setting unless the visitor picked light,
 * and always when they picked dark (data-theme on <html>).
 */
export function toCss(tokens) {
  const { space, radius, font } = tokens.primitive;
  const scale = [...flatten(space, 'space'), ...flatten(radius, 'radius'), ...flatten(font, 'font')];
  const light = Object.entries(resolveTheme(tokens, 'light'));
  const dark = Object.entries(resolveTheme(tokens, 'dark'));
  return [
    '/* Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit by hand. */',
    `:root {\n${cssVars(scale)}\n${cssVars(light)}\n  color-scheme: light;\n}`,
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light']) {\n${cssVars(dark, '    ')}\n    color-scheme: dark;\n  }\n}`,
    `:root[data-theme='dark'] {\n${cssVars(dark)}\n  color-scheme: dark;\n}`,
    '',
  ].join('\n\n');
}

/** WCAG 2.x relative luminance of a #rrggbb color. */
export function luminance(hex) {
  const channels = hex
    .replace('#', '')
    .match(/.{2}/g)
    .map((c) => parseInt(c, 16) / 255)
    .map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * channels[0] + 0.7152 * channels[1] + 0.0722 * channels[2];
}

/** WCAG contrast ratio between two #rrggbb colors, from 1 to 21. */
export function contrast(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

/** Check every declared contrast pair in both themes. */
export function checkContrast(tokens) {
  return THEMES.flatMap((theme) => {
    const values = resolveTheme(tokens, theme);
    return tokens.contrastPairs.map(({ fg, bg, min }) => {
      const ratio = contrast(values[fg], values[bg]);
      return { theme, fg, bg, min, ratio, pass: ratio >= min };
    });
  });
}
